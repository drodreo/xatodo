//! Component mode: the launch form when pulled up by the superlive v2 shell
//! under the B-plane contract.
//!
//! Fork condition: the `SL_ENDPOINT` environment variable exists
//! (slsdk_rs::ENV_ENDPOINT, injected by the shell at spawn time).
//! Differences from standalone mode:
//! - Auth: the shell gateway has already done per-component token validation,
//!   and inside the component slsdk serve re-validates with SL_TOKEN (first
//!   wall); xatodo's own apikey auth (auth.rs) is bypassed and not mounted.
//! - Users: single owner — the users table row name="local" (UUID primary
//!   key), all requests are attributed to it; users_sync is skipped (the
//!   users.entries in config.toml is the authority source for standalone
//!   deployment).
//! - Listening: SL_ENDPOINT (uds:/tcp:) is parsed and bound by slsdk serve,
//!   with graceful shutdown on SIGTERM; config.server.listen is unused
//!   (config.toml must still exist, database_url is where data lands; note
//!   Config parsing rigidity — although the listen and [users] sections are
//!   not consumed, parsing fails outright when they are missing. The minimal
//!   config inside the component package needs all three elements: listen
//!   placeholder + database_url + users.entries=[]; the packaging script
//!   generates a dedicated minimal config that carries no real apikey from
//!   standalone deployment).
//! - Identity alignment: COMPONENT_ID doubles as the health loop key (the
//!   shell matches manifest.id) and the registry dispatch key (namespace) —
//!   the manifest generated by the packaging script must be derived from the
//!   same source as this constant.
//!
//! The data layer (entity/migration/service) and the REST/MCP routes are
//! fully reused with zero changes: under shell forwarding semantics the
//! component receives its own complete path space (/api/v1/todos, /mcp).

use axum::extract::{Request, State};
use axum::middleware::Next;
use axum::response::Response;
use axum::Router;
use log::info;
use sea_orm::{ActiveModelTrait, ColumnTrait, DatabaseConnection, EntityTrait, QueryFilter, Set};
use slsdk_rs::{ComponentManifest, LaunchConfig, UiDeclaration, UiType};
use uuid::Uuid;
use xa_todo_entity as entity;

use crate::router;
use crate::state::AppState;

/// Username of the component-mode default owner: in component mode all
/// requests are attributed to this user.
pub const LOCAL_OWNER_NAME: &str = "local";

/// Whether we are in component mode (launched by the shell): true iff
/// `SL_ENDPOINT` exists.
pub fn is_component_mode() -> bool {
    component_mode(std::env::var(slsdk_rs::ENV_ENDPOINT).ok().as_deref())
}

/// Pure function for mode detection (thin wrapper over env reading, so tests
/// do not pollute the process environment).
fn component_mode(endpoint_env: Option<&str>) -> bool {
    endpoint_env.is_some()
}

/// Component mode startup: ensure the default owner → assemble routes (owner
/// injection replaces apikey auth) → slsdk serve.
/// Blocks until graceful shutdown (SIGTERM is handled by serve's built-in
/// listener; the UDS socket file is cleaned up on exit).
///
/// serve_with_events: mounts the standard /events endpoint (NDJSON push
/// stream) sharing the same A2uiNotifier instance as AppState — the
/// notify_todos_changed push after service-layer create/update/delete reaches
/// all subscribers through it (shell bridge → live refresh on every surface).
pub async fn run(db: DatabaseConnection) -> anyhow::Result<()> {
    let owner = ensure_local_owner(&db).await?;
    info!("Component mode: default owner ready (id = {})", owner.id);

    let state = AppState::new(db);
    let app = build_component_router(state.clone(), owner);
    let manifest = component_manifest();
    let serve_info =
        slsdk_rs::serve_with_events(app, &manifest, None, state.notifier.clone()).await?;
    info!("Component service started: {}", serve_info.endpoint);

    // serve's return value: awaits completion of the accept/serve loop
    // (returns after graceful shutdown)
    serve_info.wait().await?;
    Ok(())
}

/// Ensures the default owner exists and returns it: looks up by name="local",
/// inserts on miss (UUID primary key).
/// The apikey field (unique, non-null) is filled with a random UUID — in
/// component mode apikey does not participate in auth.
pub async fn ensure_local_owner(db: &DatabaseConnection) -> anyhow::Result<entity::user::Model> {
    let existing = entity::user::Entity::find()
        .filter(entity::user::Column::Name.eq(LOCAL_OWNER_NAME))
        .one(db)
        .await?;
    if let Some(user) = existing {
        return Ok(user);
    }
    let user = entity::user::ActiveModel {
        id: Set(Uuid::new_v4()),
        name: Set(LOCAL_OWNER_NAME.to_string()),
        apikey: Set(Uuid::new_v4().to_string()),
        role: Set(entity::user::UserRole::User),
        created_at: Set(chrono::Utc::now()),
    }
    .insert(db)
    .await?;
    info!("Component mode: default owner \"{LOCAL_OWNER_NAME}\" created");
    Ok(user)
}

/// Component-mode router: business routes (REST + MCP) + owner injection
/// middleware (replacing apikey auth).
/// /health is mounted by slsdk serve (SDK-reserved path; business routes must
/// not register the same path).
pub fn build_component_router(state: AppState, owner: entity::user::Model) -> Router {
    router::business_routes(state)
        .route_layer(axum::middleware::from_fn_with_state(owner, inject_owner))
}

/// Owner injection middleware: performs no auth, puts the default owner
/// entity into the request extensions.
/// The injection shape is identical to standalone-mode auth_middleware —
/// downstream handlers extract the user via Extension, unaware of the mode
/// difference.
async fn inject_owner(
    State(owner): State<entity::user::Model>,
    mut req: Request,
    next: Next,
) -> Response {
    req.extensions_mut().insert(owner);
    next.run(req).await
}

/// Synthesized manifest: the serve() contract only consumes id / version
/// (in the /health response body); the component process holds no manifest
/// file (the shell keeps it after installation), and the remaining fields are
/// filled with placeholders to satisfy construction.
/// Identity is self-reported by the component and cross-checked by the shell
/// via the health response — consistent with the contract comments in serve.rs.
/// Note: empty files would fail manifest::validate(), but serve() does not
/// call validate (safe at runtime).
fn component_manifest() -> ComponentManifest {
    ComponentManifest {
        id: crate::COMPONENT_ID.to_string(),
        version: env!("CARGO_PKG_VERSION").to_string(),
        min_shell_version: "0.0.0".to_string(),
        namespace: crate::COMPONENT_ID.to_string(),
        display_name: "xatodo".to_string(),
        ui: Some(UiDeclaration {
            ui_type: UiType::Surface,
            entry: "surface.json".to_string(),
        }),
        menu: None,
        routes: Vec::new(),
        // None = accept all transports the host platform provides (Cargo
        // template default semantics)
        transport: None,
        launch: Some(LaunchConfig {
            command: String::new(),
            args: Vec::new(),
        }),
        files: Vec::new(),
        config: None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use axum::body::Body;
    use axum::http::{Request as HttpRequest, StatusCode};
    use std::path::PathBuf;
    use tower::ServiceExt; // oneshot
    use xa_todo_migration::{Migrator, MigratorTrait};

    /// Sets up a temp sqlite file DB that is migration-ready (under /tmp,
    /// deleted when the test finishes).
    async fn test_db(tag: &str) -> (DatabaseConnection, PathBuf) {
        let path =
            std::env::temp_dir().join(format!("xatodo-component-test-{tag}-{}.db", Uuid::new_v4()));
        let url = format!("sqlite://{}?mode=rwc", path.display());
        let db = sea_orm::Database::connect(&url)
            .await
            .expect("connect test db");
        Migrator::up(&db, None).await.expect("migrate test db");
        (db, path)
    }

    /// Deletes the test DB file (unlink works even with the connection open;
    /// on failure /tmp self-cleaning is the fallback).
    fn cleanup(path: &PathBuf) {
        let _ = std::fs::remove_file(path);
    }

    #[test]
    fn component_mode_detection() {
        assert!(component_mode(Some("uds:/tmp/xatodo.sock")));
        assert!(component_mode(Some("tcp:127.0.0.1:0")));
        assert!(!component_mode(None));
    }

    #[test]
    fn endpoint_parsing() {
        // Pin down the component side's understanding of B-plane contract
        // descriptors: uds / tcp / invalid, three forms
        let ep: slsdk_rs::Endpoint = "uds:/tmp/xatodo.sock".parse().unwrap();
        assert_eq!(
            ep,
            slsdk_rs::Endpoint::Uds {
                path: "/tmp/xatodo.sock".to_string()
            }
        );

        let ep: slsdk_rs::Endpoint = "tcp:127.0.0.1:39877".parse().unwrap();
        assert_eq!(
            ep,
            slsdk_rs::Endpoint::Tcp {
                addr: "127.0.0.1:39877".parse().unwrap()
            }
        );

        assert!("xatodo.sock".parse::<slsdk_rs::Endpoint>().is_err());
    }

    #[tokio::test]
    async fn local_owner_created_once() {
        let (db, path) = test_db("owner").await;
        let first = ensure_local_owner(&db).await.unwrap();
        assert_eq!(first.name, LOCAL_OWNER_NAME);

        // Repeated ensure must reuse the same owner, and the table holds
        // exactly one row
        let second = ensure_local_owner(&db).await.unwrap();
        assert_eq!(
            first.id, second.id,
            "repeated ensure must reuse the same owner"
        );
        let all = entity::user::Entity::find().all(&db).await.unwrap();
        assert_eq!(all.len(), 1);
        cleanup(&path);
    }

    #[tokio::test]
    async fn component_router_serves_owner_without_apikey() {
        let (db, path) = test_db("router").await;
        let owner = ensure_local_owner(&db).await.unwrap();
        let app = build_component_router(AppState::new(db), owner);

        // Reachable without an Authorization header: apikey auth is bypassed
        // (token validation is handled at the slsdk serve layer)
        let res = app
            .clone()
            .oneshot(
                HttpRequest::builder()
                    .uri("/api/v1/me")
                    .body(Body::empty())
                    .unwrap(),
            )
            .await
            .unwrap();
        assert_eq!(res.status(), StatusCode::OK);
        let bytes = axum::body::to_bytes(res.into_body(), usize::MAX)
            .await
            .unwrap();
        let me: serde_json::Value = serde_json::from_slice(&bytes).unwrap();
        assert_eq!(me["name"], LOCAL_OWNER_NAME);

        // Write path: created todo is attributed to the default owner
        let res = app
            .oneshot(
                HttpRequest::builder()
                    .method("POST")
                    .uri("/api/v1/todos")
                    .header("content-type", "application/json")
                    .body(Body::from(r#"{"title":"component mode smoke"}"#))
                    .unwrap(),
            )
            .await
            .unwrap();
        assert_eq!(res.status(), StatusCode::CREATED);
        let bytes = axum::body::to_bytes(res.into_body(), usize::MAX)
            .await
            .unwrap();
        let todo: serde_json::Value = serde_json::from_slice(&bytes).unwrap();
        assert_eq!(todo["title"], "component mode smoke");

        cleanup(&path);
    }

    #[tokio::test]
    async fn component_router_serves_mcp() {
        let (db, path) = test_db("mcp").await;
        let owner = ensure_local_owner(&db).await.unwrap();
        let app = build_component_router(AppState::new(db), owner);

        // The MCP path works as usual in component mode (owner injection,
        // one request one response)
        let payload = serde_json::json!({
            "jsonrpc": "2.0",
            "id": 1,
            "method": "tools/list"
        });
        let res = app
            .oneshot(
                HttpRequest::builder()
                    .method("POST")
                    .uri("/mcp")
                    .header("content-type", "application/json")
                    .body(Body::from(payload.to_string()))
                    .unwrap(),
            )
            .await
            .unwrap();
        assert_eq!(res.status(), StatusCode::OK);
        let bytes = axum::body::to_bytes(res.into_body(), usize::MAX)
            .await
            .unwrap();
        let rpc: serde_json::Value = serde_json::from_slice(&bytes).unwrap();
        assert_eq!(rpc["jsonrpc"], "2.0");
        assert!(
            rpc["result"]["tools"].is_array(),
            "tools/list should return an array of tools"
        );

        cleanup(&path);
    }
}
